-- hr — schema
--
-- Primary keys and referential foreign keys only. No secondary indexes: Chapter 25
-- (window functions) and Chapter 12 (recursive CTEs) are more instructive when the
-- reader can see the plan change after adding one.

\set ON_ERROR_STOP on

BEGIN;

DROP TABLE IF EXISTS salary_history, employees, departments CASCADE;

CREATE TABLE departments (
    dept_id         integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            text          NOT NULL,
    location        text          NOT NULL,
    cost_center     text          NOT NULL,
    parent_dept_id  integer       REFERENCES departments(dept_id),  -- second, shallower hierarchy
    annual_budget   numeric(12,2)                                   -- nullable on purpose
);

CREATE TABLE employees (
    emp_id         integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      text          NOT NULL,
    email          text          NOT NULL,
    dept_id        integer       NOT NULL REFERENCES departments(dept_id),
    manager_id     integer       REFERENCES employees(emp_id),  -- NULL for the CEO only
    job_title      text          NOT NULL,
    hire_date      date          NOT NULL,
    salary         numeric(10,2) NOT NULL,
    status         text          NOT NULL,   -- active|on_leave|terminated
    terminated_on  date                      -- nullable on purpose
);

CREATE TABLE salary_history (
    id              integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id          integer       NOT NULL REFERENCES employees(emp_id),
    effective_date  date          NOT NULL,
    salary          numeric(10,2) NOT NULL,
    reason          text          NOT NULL   -- hire|merit|promotion|market_adjustment
);

COMMIT;
