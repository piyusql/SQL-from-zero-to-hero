-- telemetry — schema
--
-- One dimension table and one very large fact table. NOT partitioned and NOT indexed
-- beyond the primary keys, on purpose:
--   Chapter 33 asks the reader to build the indexes.
--   Chapter 34 asks them to read the plans before and after.
--   Chapter 38 asks them to partition device_events by month themselves.
-- Note there is no index on device_events.device_id — PostgreSQL does not create one
-- for a foreign key, and discovering that is Practice Session 33.1.

\set ON_ERROR_STOP on

BEGIN;

DROP TABLE IF EXISTS device_events, devices CASCADE;

CREATE TABLE devices (
    device_id          integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial             text        NOT NULL,
    model              text        NOT NULL,
    firmware           text        NOT NULL,
    site               text        NOT NULL,
    region             text        NOT NULL,
    installed_at       timestamptz NOT NULL,
    decommissioned_at  timestamptz             -- NULL for devices still in service
);

CREATE TABLE device_events (
    event_id      bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id     integer       NOT NULL REFERENCES devices(device_id),
    recorded_at   timestamptz   NOT NULL,  -- even spread across the window; the
                                           -- natural partition key for Chapter 38
    metric_name   text          NOT NULL,  -- temp_c|humidity_pct|battery_v|rssi_dbm|pressure_hpa
    metric_value  numeric(12,3) NOT NULL,
    payload       jsonb         NOT NULL,  -- Chapter 17 works on this column
    severity      text                     -- NULL on the ~90% of events that are routine
);

COMMIT;
