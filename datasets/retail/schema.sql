-- retail — schema
--
-- Deliberately minimal: primary keys and the foreign keys needed for referential
-- sanity. No secondary indexes, no UNIQUE constraints, no partitioning. Several
-- chapters (33 Indexing, 34 EXPLAIN, 38 Partitioning) ask the reader to add those
-- and measure the difference. A pre-tuned dataset kills those exercises.

\set ON_ERROR_STOP on

BEGIN;

DROP TABLE IF EXISTS order_items, orders, customers, products CASCADE;

CREATE TABLE products (
    id          integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         text          NOT NULL,
    name        text          NOT NULL,
    category    text          NOT NULL,
    price       numeric(10,2) NOT NULL,
    in_stock    boolean       NOT NULL DEFAULT true,
    created_at  timestamptz   NOT NULL
);

CREATE TABLE customers (
    id            integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text        NOT NULL,
    email         text        NOT NULL,
    country       text        NOT NULL,   -- ISO 3166-1 alpha-2; 'IN' dominates, ~60%
    city          text,                   -- nullable on purpose
    signup_date   date        NOT NULL,
    loyalty_tier  text,                   -- nullable on purpose
    referred_by   integer     REFERENCES customers(id)  -- nullable self-reference:
                                          -- this is the column the Chapter 7 NOT IN
                                          -- trap and Practice Session 10.2 run on
);

CREATE TABLE orders (
    id             integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    integer       NOT NULL REFERENCES customers(id),
    placed_at      timestamptz   NOT NULL,
    shipped_at     timestamptz,             -- NULL while unshipped or cancelled
    status         text          NOT NULL,  -- pending|paid|shipped|delivered|cancelled|returned
    discount_code  text,                    -- nullable on purpose
    total_amount   numeric(12,2) NOT NULL   -- denormalised: equals SUM over order_items.
                                            -- This is what makes the Chapter 9 fan-out
                                            -- exercise (9.4) possible.
);

CREATE TABLE order_items (
    id          integer       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    integer       NOT NULL REFERENCES orders(id),
    product_id  integer       NOT NULL REFERENCES products(id),
    quantity    integer       NOT NULL,
    unit_price  numeric(10,2) NOT NULL   -- price at time of sale, not products.price
);

COMMIT;
